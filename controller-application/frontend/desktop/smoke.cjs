// Real Electron UI check, used by integration.mjs with isolated local services.
const { app } = require('electron')
const { registerProtocol, createWindow } = require('./main.cjs')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')

if (!process.env.YCG_SMOKE_PROFILE || !process.env.YCG_SMOKE_VIDEOS) throw new Error('Run through integration.mjs')
app.setPath('userData', process.env.YCG_SMOKE_PROFILE)
app.disableHardwareAcceleration()

app.whenReady().then(async () => {
  registerProtocol()
  const window = createWindow({ show: false })
  const wc = window.webContents
  const evaluate = code => wc.executeJavaScript(code)
  const waitFor = async (code, target = wc) => {
    const until = Date.now() + 60000
    while (Date.now() < until) {
      if (await target.executeJavaScript(code)) return
      await new Promise(resolve => setTimeout(resolve, 100))
    }
    throw new Error('UI condition timed out: ' + code + '\n' + await target.executeJavaScript('document.body.innerText'))
  }
  try {
    await waitFor('!!document.querySelector("#action")')
    await evaluate(`document.querySelector('#action').value='chapters'; document.querySelector('#action').dispatchEvent(new Event('change', {bubbles:true}))`)
    await waitFor(`!!document.querySelector('input[type=file]')`)
    assert.equal(await evaluate(`document.querySelector('.video-footer button').disabled`), true)
    wc.debugger.attach('1.3')
    await wc.debugger.sendCommand('DOM.enable')
    const doc = await wc.debugger.sendCommand('DOM.getDocument')
    const input = await wc.debugger.sendCommand('DOM.querySelector', { nodeId: doc.root.nodeId, selector: 'input[type=file]' })
    await evaluate(`document.querySelector('input[type=file]').addEventListener('change', e => {window.smokeFiles=Array.from(e.target.files)}, {capture:true})`)
    const videos = JSON.parse(process.env.YCG_SMOKE_VIDEOS)
    await wc.debugger.sendCommand('DOM.setFileInputFiles', { nodeId: input.nodeId, files: videos })
    await waitFor(`document.querySelectorAll('.video-list li').length===2`)
    assert.equal(await evaluate(`window.ycgDesktop.getPathForFile(window.smokeFiles[0])`), videos[0])
    assert.equal(await evaluate(`document.querySelector('.video-footer button').disabled`), true)
    await evaluate(`Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(document.querySelector('#game-name'),'Smoke game'); document.querySelector('#game-name').dispatchEvent(new Event('input',{bubbles:true}))`)
    await waitFor(`!document.querySelector('.video-footer button').disabled`)
    await evaluate(`document.querySelectorAll('.video-list button').forEach(button=>button.click())`)
    await waitFor(`document.querySelector('.video-footer button').disabled && !document.querySelector('.video-list')`)
    // The dropped File objects still originate from native disk selection.
    await evaluate(`{ const data=new DataTransfer(); window.smokeFiles.forEach(file=>data.items.add(file)); document.querySelector('.drop-zone').dispatchEvent(new DragEvent('drop',{bubbles:true,dataTransfer:data})); }`)
    await waitFor(`document.querySelectorAll('.video-list li').length===2`)
    await evaluate(`document.querySelector('.video-footer button').click()`)
    await waitFor(`document.body.innerText.includes('No knowledge base exists for') && !document.querySelector('.video-footer button').disabled`)
    assert.equal(await evaluate(`localStorage.getItem('ycg.lastProxyJob')`), null)
    await evaluate(`document.querySelector('#action').value='knowledge'; document.querySelector('#action').dispatchEvent(new Event('change', {bubbles:true}))`)
    await waitFor(`!!document.querySelector('button[type=submit]')`)
    await evaluate(`document.querySelector('button[type=submit]').click()`)
    await waitFor(`document.body.innerText.includes('Knowledge base saved successfully.') && !document.querySelector('button[type=submit]').disabled`)
    assert.ok((await evaluate('document.body.innerText')).includes(process.env.YCG_SMOKE_KNOWLEDGE_PATH))
    const firstKnowledge = await fs.readFile(process.env.YCG_SMOKE_KNOWLEDGE_PATH, 'utf8')
    await evaluate(`document.querySelector('button[type=submit]').click()`)
    await waitFor(`document.querySelector('dialog').open`)
    await evaluate(`document.querySelector('.dialog-actions .text-button').click()`)
    await waitFor(`!document.querySelector('dialog').open && !document.querySelector('button[type=submit]').disabled`)
    assert.equal(await fs.readFile(process.env.YCG_SMOKE_KNOWLEDGE_PATH, 'utf8'), firstKnowledge)
    await evaluate(`document.querySelector('button[type=submit]').click()`)
    await waitFor(`document.querySelector('dialog').open`)
    await evaluate(`document.querySelector('.dialog-actions .primary-button').click()`)
    await waitFor(`!document.querySelector('dialog').open && !document.querySelector('button[type=submit]').disabled`)
    const rebuilt = JSON.parse(await fs.readFile(process.env.YCG_SMOKE_KNOWLEDGE_PATH, 'utf8'))
    assert.equal(rebuilt.bosses[0].displayName, 'Test boss 2')
    await evaluate(`document.querySelector('#action').value='chapters'; document.querySelector('#action').dispatchEvent(new Event('change', {bubbles:true}))`)
    await waitFor(`!!document.querySelector('.video-footer button')`)
    await evaluate(`document.querySelector('.video-footer button').click()`)
    await waitFor(`document.body.innerText.includes('Boss fight intervals have been determined for all videos.')`)
    const text = await evaluate('document.body.innerText')
    assert.equal((text.match(/FFmpeg command:/g) || []).length, 6)
    assert.ok(text.includes('proxy ready'))
    assert.equal((text.match(/sampled frames ready \(1\)/g) || []).length, 2)
    assert.equal((text.match(/boss fight analysis ready \(1 frames\)/g) || []).length, 2)
    assert.equal((text.match(/Boss fight #1: 00:00:00.000 -> 00:00:04.000/g) || []).length, 2)
    assert.equal(await evaluate(`document.querySelector('.video-footer button').disabled`), false)
    // Page reload must replay the persisted commands and terminal state.
    wc.reload()
    await waitFor(`document.body.innerText.includes('Boss fight intervals have been determined for all videos.')`)
    const replayed = await evaluate('document.body.innerText')
    assert.equal((replayed.match(/FFmpeg command:/g) || []).length, 6)
    assert.equal((replayed.match(/sampled frames ready \(1\)/g) || []).length, 2)
    assert.equal((replayed.match(/boss fight analysis ready \(1 frames\)/g) || []).length, 2)
    assert.equal((replayed.match(/Boss fight #1: 00:00:00.000 -> 00:00:04.000/g) || []).length, 2)
    // An old persisted job must not replay its start/failure when the app opens anew.
    const oldJobId = await evaluate(`sessionStorage.getItem('ycg.currentProxyJob')`)
    await evaluate(`localStorage.setItem('ycg.lastProxyJob', sessionStorage.getItem('ycg.currentProxyJob'))`)
    const fresh = createWindow({ show: false })
    await waitFor(`!!document.querySelector('#action') && localStorage.getItem('ycg.lastProxyJob') === null`, fresh.webContents)
    const freshText = await fresh.webContents.executeJavaScript('document.body.innerText')
    assert.ok(oldJobId)
    assert.ok(freshText.includes('Workspace ready.'))
    assert.ok(!freshText.includes('Video preprocessing started.'))
    assert.ok(!freshText.includes('Boss fight intervals have been determined for all videos.'))
    fresh.close()
    // A failed video emits both a stage failure and a terminal job failure.
    // The activity log should show one error while the journal retains both.
    await evaluate(`document.querySelector('#action').value='chapters'; document.querySelector('#action').dispatchEvent(new Event('change', {bubbles:true}))`)
    await waitFor(`!!document.querySelector('input[type=file]')`)
    await evaluate(`Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(document.querySelector('#game-name'),'Smoke game'); document.querySelector('#game-name').dispatchEvent(new Event('input',{bubbles:true}))`)
    const badDoc = await wc.debugger.sendCommand('DOM.getDocument')
    const badInput = await wc.debugger.sendCommand('DOM.querySelector', { nodeId: badDoc.root.nodeId, selector: 'input[type=file]' })
    await wc.debugger.sendCommand('DOM.setFileInputFiles', { nodeId: badInput.nodeId, files: [process.env.YCG_SMOKE_BAD_VIDEO] })
    await waitFor(`document.querySelectorAll('.video-list li').length===1 && !document.querySelector('.video-footer button').disabled`)
    await evaluate(`document.querySelector('.video-footer button').click()`)
    await waitFor(`document.body.innerText.includes('bad-video.mp4: proxy creation failed:') && !document.querySelector('.video-footer button').disabled`)
    const errors = await evaluate(`Array.from(document.querySelectorAll('.log-entry')).filter(entry => entry.querySelector('.log-level')?.textContent === 'error').map(entry => entry.querySelector('.log-message')?.textContent)`)
    assert.equal(errors.filter(message => message.includes('bad-video.mp4')).length, 1)
    if (process.env.YCG_SMOKE_SCREENSHOT) {
      await fs.writeFile(process.env.YCG_SMOKE_SCREENSHOT, (await wc.capturePage()).toPNG())
    }
    console.log('DESKTOP_SMOKE_OK: native paths, two proxy/sample pairs, reload replay, and one visible failure')
    app.exit(0)
  } catch (error) {
    console.error(error)
    app.exit(1)
  }
})
